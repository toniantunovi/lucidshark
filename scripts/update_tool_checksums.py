#!/usr/bin/env python3
"""Regenerate the pinned SHA-256 table for every tool LucidShark downloads.

Usage:
    python scripts/update_tool_checksums.py          # download, hash, write
    python scripts/update_tool_checksums.py --check  # offline: URL set in sync?

The URLs are not templated here. They are captured from each plugin's own
``_download_binary`` for every supported platform, so the table can never
drift from what the plugins actually request.

Every hash is cross-checked against the ``digest`` GitHub records for the
release asset at upload time, when GitHub has one. A mismatch aborts.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys
import tempfile
from pathlib import Path
from typing import Any, Dict, List, Optional, Set
from unittest import mock
from urllib.parse import quote
from urllib.request import Request

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from lucidshark.bootstrap.download import get_ssl_context  # noqa: E402
from lucidshark.bootstrap.platform import PlatformInfo  # noqa: E402

CHECKSUMS_FILE = ROOT / "src" / "lucidshark" / "bootstrap" / "checksums.py"

from lucidshark.plugins.duplication.duplo import DuploPlugin  # noqa: E402
from lucidshark.plugins.linters.checkstyle import CheckstyleLinter  # noqa: E402
from lucidshark.plugins.linters.ktlint import KtlintLinter  # noqa: E402
from lucidshark.plugins.linters.pmd import PmdLinter  # noqa: E402
from lucidshark.plugins.scanners.checkov import CheckovScanner  # noqa: E402
from lucidshark.plugins.scanners.gosec import GosecScanner  # noqa: E402
from lucidshark.plugins.scanners.opengrep import OpenGrepScanner  # noqa: E402
from lucidshark.plugins.scanners.trivy import TrivyScanner  # noqa: E402
from lucidshark.plugins.type_checkers.detekt import DetektChecker  # noqa: E402
from lucidshark.plugins.type_checkers.spotbugs import SpotBugsChecker  # noqa: E402

# Every plugin that downloads a binary. Adding a downloading plugin means adding it here.
PLUGINS: List[Any] = [
    TrivyScanner,
    OpenGrepScanner,
    CheckovScanner,
    GosecScanner,
    PmdLinter,
    CheckstyleLinter,
    KtlintLinter,
    SpotBugsChecker,
    DetektChecker,
    DuploPlugin,
]

PLATFORMS = [
    ("linux", "amd64"),
    ("linux", "arm64"),
    ("darwin", "amd64"),
    ("darwin", "arm64"),
]

HEADER = '''"""Pinned SHA-256 digests for every tool asset LucidShark downloads.

GENERATED by scripts/update_tool_checksums.py. Do not edit by hand.
Regenerate after changing any version in [tool.lucidshark.tools].
"""

from __future__ import annotations

from typing import Dict

'''


class _Captured(Exception):
    """Raised in place of the network call once the URL is known."""


def collect_download_urls() -> Dict[str, Set[str]]:
    """Return {plugin class name: URLs it downloads across all platforms}."""
    result: Dict[str, Set[str]] = {}
    with tempfile.TemporaryDirectory() as tmp:
        for cls in PLUGINS:
            module = sys.modules[cls.__module__]
            class_name = cls.__name__
            urls: Set[str] = set()
            for os_name, arch in PLATFORMS:
                seen: List[str] = []

                def _capture(url: str, *args: object, **kwargs: object) -> bytes:
                    seen.append(url)
                    raise _Captured(url)

                patches = [
                    mock.patch.object(module, "download_verified", side_effect=_capture)
                ]
                if hasattr(module, "get_platform_info"):
                    patches.append(
                        mock.patch.object(
                            module,
                            "get_platform_info",
                            return_value=PlatformInfo(os=os_name, arch=arch),
                        )
                    )
                for p in patches:
                    p.start()
                try:
                    plugin = cls(project_root=Path(tmp))
                    plugin._download_binary(Path(tmp) / "bin" / class_name)
                except Exception:  # plugins wrap download errors in their own types
                    pass
                finally:
                    for p in patches:
                        p.stop()
                if len(seen) != 1:
                    raise SystemExit(
                        f"{class_name} on {os_name}-{arch}: expected 1 download, saw {seen}"
                    )
                urls.add(seen[0])
            if not urls:
                raise SystemExit(f"{class_name}: captured no download URL")
            result[class_name] = urls
    return result


def _open(url: str, accept: Optional[str] = None):
    from urllib.request import urlopen

    if not url.startswith("https://"):
        raise ValueError(url)
    headers = {"User-Agent": "lucidshark-checksum-updater"}
    if accept:
        headers["Accept"] = accept
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token and url.startswith("https://api.github.com/"):
        headers["Authorization"] = f"Bearer {token}"
    request = Request(url, headers=headers)
    # URL scheme is checked above: https only, so no file:// access.
    return urlopen(request, timeout=300, context=get_ssl_context())  # nosec B310  # nosemgrep


def sha256_of_url(url: str) -> str:
    from urllib.error import HTTPError

    h = hashlib.sha256()
    try:
        with _open(url) as resp:
            for chunk in iter(lambda: resp.read(1 << 20), b""):
                h.update(chunk)
    except HTTPError as e:
        raise SystemExit(
            f"HTTP {e.code} for {url}\n"
            "The asset is missing upstream: the plugin's asset template or the pinned version needs changing."
        ) from e
    return h.hexdigest()


_release_cache: Dict[str, dict] = {}


def github_digest(url: str) -> Optional[str]:
    """SHA-256 GitHub recorded for this release asset, or None if unavailable."""
    prefix = "https://github.com/"
    marker = "/releases/download/"
    if not url.startswith(prefix) or marker not in url:
        return None
    repo, rest = url[len(prefix) :].split(marker, 1)
    tag, name = rest.rsplit("/", 1)
    key = f"{repo}@{tag}"
    if key not in _release_cache:
        api = f"https://api.github.com/repos/{repo}/releases/tags/{quote(tag, safe='')}"
        with _open(api, accept="application/vnd.github+json") as resp:
            _release_cache[key] = json.loads(resp.read().decode("utf-8"))
    for asset in _release_cache[key].get("assets", []):
        if asset.get("name") == name:
            digest = asset.get("digest") or ""
            return digest.split(":", 1)[1] if digest.startswith("sha256:") else None
    raise SystemExit(f"asset {name} not found in release {key}")


def load_current() -> Dict[str, str]:
    namespace: dict = {}
    exec(compile(CHECKSUMS_FILE.read_text(), str(CHECKSUMS_FILE), "exec"), namespace)  # nosec B102  # nosemgrep
    return dict(namespace["PINNED_SHA256"])


def render(pins: Dict[str, str]) -> str:
    lines = [HEADER, "PINNED_SHA256: Dict[str, str] = {\n"]
    for url in sorted(pins):
        lines.append(f'    "{url}": (\n        "{pins[url]}"\n    ),\n')
    lines.append("}\n")
    return "".join(lines)


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="offline: fail if the pinned URL set is out of sync",
    )
    args = parser.parse_args(argv)

    by_plugin = collect_download_urls()
    wanted = set().union(*by_plugin.values())
    current = load_current()

    if args.check:
        missing = sorted(wanted - set(current))
        stale = sorted(set(current) - wanted)
        for url in missing:
            print(f"MISSING pin: {url}")
        for url in stale:
            print(f"STALE pin:   {url}")
        if missing or stale:
            print("Run: python scripts/update_tool_checksums.py")
            return 1
        print(f"in sync: {len(wanted)} pinned assets")
        return 0

    pins: Dict[str, str] = {}
    for url in sorted(wanted):
        actual = sha256_of_url(url)
        upstream = github_digest(url)
        if upstream is not None and upstream != actual:
            raise SystemExit(
                f"GitHub digest mismatch for {url}: github={upstream} downloaded={actual}"
            )
        if url in current and current[url] != actual:
            raise SystemExit(
                f"Pinned hash changed for an unchanged URL (asset replaced upstream?): {url}\n"
                f"  pinned={current[url]}\n  now={actual}\n"
                "Investigate before re-pinning; delete the line by hand only if the change is legitimate."
            )
        note = "github digest ok" if upstream else "no github digest"
        print(f"{actual}  {url}  ({note})")
        pins[url] = actual

    CHECKSUMS_FILE.write_text(render(pins))
    print(f"wrote {len(pins)} pins to {CHECKSUMS_FILE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
